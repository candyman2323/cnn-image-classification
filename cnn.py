# Import the required libraries

import os
import numpy as np
import matplotlib.pyplot as plt
import tensorflow as tf

from tensorflow.keras.preprocessing.image import ImageDataGenerator
from tensorflow.keras.models import Sequential
from tensorflow.keras.layers import Conv2D, MaxPooling2D, Flatten, Dense, Dropout

# Check TensorFlow version and GPU availability

print("TensorFlow version:", tf.__version__)
print("GPU:", tf.config.list_physical_devices("GPU"))

# Upload the dataset ZIP file

from google.colab import files

uploaded = files.upload()

# Extract the ZIP file

import zipfile

zip_file = list(uploaded.keys())[0]

with zipfile.ZipFile(zip_file, "r") as zip_ref:
    zip_ref.extractall("/content/dataset")

print("Dataset extracted")

# Set the paths for training and testing data

train_dir = "/content/dataset/seg_train/seg_train"
test_dir = "/content/dataset/seg_test/seg_test"

print(train_dir)
print(test_dir)

# Check the different image classes

classes = os.listdir(train_dir)

print("Classes:", classes)
print("Number of classes:", len(classes))

# Count the number of images in each class

for class_name in classes:
    path = os.path.join(train_dir, class_name)
    print(class_name, ":", len(os.listdir(path)))

# Display one image from each class

plt.figure(figsize=(10, 6))

for i, class_name in enumerate(classes):
    path = os.path.join(train_dir, class_name)
    image_name = os.listdir(path)[0]
    image = plt.imread(os.path.join(path, image_name))

    plt.subplot(2, 3, i + 1)
    plt.imshow(image)
    plt.title(class_name)
    plt.axis("off")

plt.show()

# Resize images and normalize pixel values

train_datagen = ImageDataGenerator(
    rescale=1./255,
    validation_split=0.2
)

test_datagen = ImageDataGenerator(
    rescale=1./255
)

# Load 80% of the training images for training

train_data = train_datagen.flow_from_directory(
    train_dir,
    target_size=(150, 150),
    batch_size=32,
    class_mode="categorical",
    subset="training"
)

# Use the remaining 20% of training images for validation

validation_data = train_datagen.flow_from_directory(
    train_dir,
    target_size=(150, 150),
    batch_size=32,
    class_mode="categorical",
    subset="validation"
)

# Load the test images

test_data = test_datagen.flow_from_directory(
    test_dir,
    target_size=(150, 150),
    batch_size=32,
    class_mode="categorical",
    shuffle=False
)

# Create a simple CNN model

model = Sequential([
    Conv2D(32, (3, 3), activation="relu", input_shape=(150, 150, 3)),
    MaxPooling2D(2, 2),

    Conv2D(64, (3, 3), activation="relu"),
    MaxPooling2D(2, 2),

    Conv2D(128, (3, 3), activation="relu"),
    MaxPooling2D(2, 2),

    Flatten(),
    Dense(128, activation="relu"),
    Dropout(0.5),

    Dense(6, activation="softmax")
])

model.summary()

# Compile the model before training

model.compile(
    optimizer="adam",
    loss="categorical_crossentropy",
    metrics=["accuracy"]
)

# Train the CNN model

history = model.fit(
    train_data,
    validation_data=validation_data,
    epochs=5
)

# Evaluate the CNN using the test data

test_loss, test_accuracy = model.evaluate(test_data)

print("Test Accuracy:", test_accuracy)

# Plot training and validation accuracy

plt.plot(history.history["accuracy"], label="Training Accuracy")
plt.plot(history.history["val_accuracy"], label="Validation Accuracy")

plt.xlabel("Epoch")
plt.ylabel("Accuracy")
plt.title("CNN Accuracy")

plt.legend()
plt.show()

# Plot training and validation loss

plt.plot(history.history["loss"], label="Training Loss")
plt.plot(history.history["val_loss"], label="Validation Loss")

plt.xlabel("Epoch")
plt.ylabel("Loss")
plt.title("CNN Loss")

plt.legend()
plt.show()

# Import the pretrained MobileNetV2 model

from tensorflow.keras.applications import MobileNetV2
from tensorflow.keras.layers import GlobalAveragePooling2D

# Load MobileNetV2 with ImageNet weights

base_model = MobileNetV2(
    weights="imagenet",
    include_top=False,
    input_shape=(150, 150, 3)
)

# Freeze the pretrained layers

base_model.trainable = False

# Add our own classification layers to MobileNetV2

transfer_model = Sequential([
    base_model,
    GlobalAveragePooling2D(),
    Dense(128, activation="relu"),
    Dropout(0.5),
    Dense(6, activation="softmax")
])

transfer_model.summary()

# Compile the transfer learning model

transfer_model.compile(
    optimizer="adam",
    loss="categorical_crossentropy",
    metrics=["accuracy"]
)

# Train the transfer learning model

transfer_history = transfer_model.fit(
    train_data,
    validation_data=validation_data,
    epochs=5
)

# Evaluate the transfer learning model

transfer_loss, transfer_accuracy = transfer_model.evaluate(test_data)

print("Transfer Learning Accuracy:", transfer_accuracy)

# Compare the CNN and transfer learning results

print("CNN Accuracy:", test_accuracy)
print("Transfer Learning Accuracy:", transfer_accuracy)

# Predict the classes of the test images

predictions = transfer_model.predict(test_data)

predicted_classes = np.argmax(predictions, axis=1)
true_classes = test_data.classes

class_names = list(test_data.class_indices.keys())

print(class_names)

# Create a confusion matrix to see the prediction errors

from sklearn.metrics import confusion_matrix
import seaborn as sns

cm = confusion_matrix(true_classes, predicted_classes)

plt.figure(figsize=(8, 6))

sns.heatmap(
    cm,
    annot=True,
    fmt="d",
    xticklabels=class_names,
    yticklabels=class_names
)

plt.xlabel("Predicted")
plt.ylabel("Actual")
plt.title("Confusion Matrix")

plt.show()

# Calculate precision, recall and F1-score

from sklearn.metrics import classification_report

print(classification_report(
    true_classes,
    predicted_classes,
    target_names=class_names
))